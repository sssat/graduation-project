  AND f.FINAL_RANK_SEQ IS NULL
GROUP BY s.TREND_RUN_SEQ, s.KEYWORD_SEQ, km.KEYWORD_NAME, p.PERIOD_FILTER
ORDER BY p.PERIOD_FILTER, s.KEYWORD_SEQ;


