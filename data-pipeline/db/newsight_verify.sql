-- 2) 스냅샷 키워드 대비 MEDIA_STAT(전체=MEDIA_CODE 0) 누락(키워드/기간별 전체 행이 있어야 한다면 0건 정상)
WITH periods2 AS (
  SELECT 'TODAY' AS PERIOD_FILTER
  UNION ALL SELECT 'D7'
  UNION ALL SELECT 'D14'
)
SELECT
  s.KEYWORD_SEQ,
  km.KEYWORD_NAME,
  p.PERIOD_FILTER
FROM T_TREND_KEYWORD_SNAPSHOT s
JOIN T_TREND_KEYWORD_MASTER km ON km.KEYWORD_SEQ = s.KEYWORD_SEQ
CROSS JOIN periods2 p
LEFT JOIN T_ANALYZE_MEDIA_STAT st
  ON st.TREND_RUN_SEQ = s.TREND_RUN_SEQ
 AND st.KEYWORD_SEQ = s.KEYWORD_SEQ
 AND st.MEDIA_CODE = 0
 AND st.PERIOD_FILTER = p.PERIOD_FILTER
WHERE s.TREND_RUN_SEQ = @run_seq
  AND st.STAT_SEQ IS NULL
GROUP BY s.KEYWORD_SEQ, km.KEYWORD_NAME, p.PERIOD_FILTER
ORDER BY p.PERIOD_FILTER, s.KEYWORD_SEQ;