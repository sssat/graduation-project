/* ----------------------------------------------------------------------
  13) T_ANALYZE_CO_MENTION_GRAPH / NODE / EDGE (공동언급 그래프)
------------------------------------------------------------------------ */

-- 1) 그래프 헤더 존재/개수
SELECT TREND_RUN_SEQ, PERIOD_FILTER,
       COUNT(*) AS graph_cnt,
       SUM(NODE_COUNT) AS sum_node_count,
       SUM(EDGE_COUNT) AS sum_edge_count
FROM T_ANALYZE_CO_MENTION_GRAPH
WHERE TREND_RUN_SEQ = @run_seq
  AND PERIOD_FILTER IN ('TODAY', 'D7', 'D14')
GROUP BY TREND_RUN_SEQ, PERIOD_FILTER;

-- 2) 헤더의 NODE_COUNT/EDGE_COUNT가 실제와 맞는지(불일치: 0건 정상)
SELECT
  g.GRAPH_SEQ,
  g.NODE_COUNT, COALESCE(n.real_nodes, 0) AS real_nodes,
  g.EDGE_COUNT, COALESCE(e.real_edges, 0) AS real_edges
FROM T_ANALYZE_CO_MENTION_GRAPH g
LEFT JOIN (
  SELECT GRAPH_SEQ, COUNT(*) AS real_nodes
  FROM T_ANALYZE_CO_MENTION_NODE
  GROUP BY GRAPH_SEQ
) n ON n.GRAPH_SEQ = g.GRAPH_SEQ
LEFT JOIN (
  SELECT GRAPH_SEQ, COUNT(*) AS real_edges
  FROM T_ANALYZE_CO_MENTION_EDGE
  GROUP BY GRAPH_SEQ
) e ON e.GRAPH_SEQ = g.GRAPH_SEQ
WHERE g.TREND_RUN_SEQ = @run_seq
  AND g.PERIOD_FILTER IN ('TODAY', 'D7', 'D14')
  AND (g.NODE_COUNT <> COALESCE(n.real_nodes, 0) OR g.EDGE_COUNT <> COALESCE(e.real_edges, 0))
ORDER BY g.GRAPH_SEQ DESC
LIMIT 200;

-- 3) EDGE가 참조하는 NODE가 실제로 존재하는지(0건 정상)
SELECT e.EDGE_SEQ
FROM T_ANALYZE_CO_MENTION_EDGE e
LEFT JOIN T_ANALYZE_CO_MENTION_NODE n1 ON n1.NODE_SEQ = e.FROM_NODE_SEQ
LEFT JOIN T_ANALYZE_CO_MENTION_NODE n2 ON n2.NODE_SEQ = e.TO_NODE_SEQ
WHERE n1.NODE_SEQ IS NULL OR n2.NODE_SEQ IS NULL
LIMIT 200;

-- 4) 동일 GRAPH 내 동일 엔티티 중복(0건 정상: UNIQUE)
SELECT GRAPH_SEQ, ENTITY_NAME, COUNT(*) AS cnt
FROM T_ANALYZE_CO_MENTION_NODE
GROUP BY GRAPH_SEQ, ENTITY_NAME
HAVING cnt > 1;

-- 5) 동일 GRAPH 내 동일 FROM-TO 중복(0건 정상: UNIQUE)
SELECT GRAPH_SEQ, FROM_NODE_SEQ, TO_NODE_SEQ, COUNT(*) AS cnt
FROM T_ANALYZE_CO_MENTION_EDGE
GROUP BY GRAPH_SEQ, FROM_NODE_SEQ, TO_NODE_SEQ
HAVING cnt > 1;


