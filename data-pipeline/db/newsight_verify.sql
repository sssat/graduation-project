-- 1) run/period 기준 감성 행 수(전체/매체별)
-- 예를들어 D14 / MEDIA_CODE=0 / rows_cnt=13 => D14 기간에서 “전체(0)” 집계 감성 결과가 13개 키워드에 대해서만 저장돼 있다는 뜻
-- 예를들어 D14 / MEDIA_CODE=1023 / rows_cnt=11 => D14에서 조선일보(1023) 감성 결과가 11개 키워드만 저장됨
SELECT TREND_RUN_SEQ, PERIOD_FILTER, MEDIA_CODE, COUNT(*) AS rows_cnt
FROM T_ANALYZE_SENTIMENT
WHERE TREND_RUN_SEQ = @run_seq
  AND PERIOD_FILTER IN ('TODAY', 'D7', 'D14')
GROUP BY TREND_RUN_SEQ, PERIOD_FILTER, MEDIA_CODE
ORDER BY PERIOD_FILTER, MEDIA_CODE;

-- 2) 제목 비율 합이 100 근처인지(라운딩 허용 오차 0.5)
-- (개선) 제목이 "미계산 상태(0,0,0)"로 저장되는 정책이 있을 수 있으므로,
--        합이 0인 행은 검사에서 제외한다.
-- 0건 정상
SELECT SENTIMENT_SEQ, TREND_RUN_SEQ, KEYWORD_SEQ, MEDIA_CODE, PERIOD_FILTER,
       (POSITIVE_PCT_TITLE + NEUTRAL_PCT_TITLE + NEGATIVE_PCT_TITLE) AS sum_title
FROM T_ANALYZE_SENTIMENT
WHERE TREND_RUN_SEQ = @run_seq
  AND PERIOD_FILTER IN ('TODAY', 'D7', 'D14')
  AND (POSITIVE_PCT_TITLE + NEUTRAL_PCT_TITLE + NEGATIVE_PCT_TITLE) > 0
  AND ABS((POSITIVE_PCT_TITLE + NEUTRAL_PCT_TITLE + NEGATIVE_PCT_TITLE) - 100) > 0.5
ORDER BY ABS((POSITIVE_PCT_TITLE + NEUTRAL_PCT_TITLE + NEGATIVE_PCT_TITLE) - 100) DESC
LIMIT 200;

-- 3) 본문 비율 합이 100 근처인지(본문 미계산이면 0일 수 있음)
-- 0건 정상
SELECT SENTIMENT_SEQ, TREND_RUN_SEQ, KEYWORD_SEQ, MEDIA_CODE, PERIOD_FILTER,
       (POSITIVE_PCT_CONTENT + NEUTRAL_PCT_CONTENT + NEGATIVE_PCT_CONTENT) AS sum_content
FROM T_ANALYZE_SENTIMENT
WHERE TREND_RUN_SEQ = @run_seq
  AND PERIOD_FILTER IN ('TODAY', 'D7', 'D14')
