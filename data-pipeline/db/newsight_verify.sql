-- data-pipeline/db/newsight_verify.sql
-- Newsight 데이터 적재/분석 결과 검증용 SQL 모음 (MySQL 8.x / utf8mb4)
-- 사용법:
-- 1) 아래 @run_seq 값을 상황에 맞게 설정
-- 2) 섹션별로 실행하면서 "0건이 정상" / "개수/합계가 기대와 일치" 여부를 확인
-- 참고: DBeaver에서 SQL 쿼리 실행할 땐 쿼리 전체를 드래그해서 선택한 후 Ctrl+Enter로 실행

/* ----------------------------------------------------------------------
  0) 공통: 검사 기준 run 변수 세팅
  - 기간(TODAY/D7/D14)은 BASE_DATE 기준 윈도우로 쿼리 내부에서 계산한다(변수 미사용).
  - TODAY 윈도우: [BASE_DATE 00:00:00, BASE_DATE + 1day 00:00:00)
  - D7    윈도우: [BASE_DATE - 6day 00:00:00, BASE_DATE + 1day 00:00:00)  (오늘 포함 7일)
  - D14   윈도우: [BASE_DATE - 13day 00:00:00, BASE_DATE + 1day 00:00:00) (오늘 포함 14일)
------------------------------------------------------------------------ */

-- 최신 run 기준으로 검증
SET @run_seq := (SELECT MAX(TREND_RUN_SEQ) FROM T_TREND_RUN);

-- 특정 run 지정 시 주석 해제 후 값만 수정
-- SET @run_seq := 11;


/* ----------------------------------------------------------------------
  1) T_NEWS_MEDIA (언론사)
------------------------------------------------------------------------ */

-- 1) 시드가 정상인지(전체 포함)
SELECT * FROM T_NEWS_MEDIA ORDER BY MEDIA_CODE;

-- 2) MEDIA_CODE 중복/이상 여부(원래 PK라 0건이 정상)
SELECT MEDIA_CODE, COUNT(*) AS cnt
FROM T_NEWS_MEDIA
GROUP BY MEDIA_CODE
HAVING cnt > 1;

-- 3) 기사/분석 테이블에 존재하는 MEDIA_CODE가 모두 마스터에 있는지(0건 정상)
-- 주의: MEDIA_CODE=0(전체 집계 행)을 사용하는 테이블이 있다면, 마스터에 0이 없을 수 있으므로 제외한다.
SELECT a.MEDIA_CODE, COUNT(*) AS cnt
FROM (
  SELECT MEDIA_CODE FROM T_NEWS_ARTICLE
  UNION ALL SELECT MEDIA_CODE FROM T_ANALYZE_MEDIA_STAT
  UNION ALL SELECT MEDIA_CODE FROM T_ANALYZE_SENTIMENT
  UNION ALL SELECT MEDIA_CODE FROM T_ANALYZE_MEDIA_BIAS
  UNION ALL SELECT MEDIA_CODE FROM T_ANALYZE_WORDCLOUD
  UNION ALL SELECT MEDIA_CODE FROM T_ANALYZE_CO_MENTION_GRAPH
) a
LEFT JOIN T_NEWS_MEDIA m ON m.MEDIA_CODE = a.MEDIA_CODE
WHERE a.MEDIA_CODE IS NOT NULL
  AND a.MEDIA_CODE <> 0
  AND m.MEDIA_CODE IS NULL
GROUP BY a.MEDIA_CODE;


/* ----------------------------------------------------------------------
  2) T_TREND_KEYWORD_MASTER (키워드 마스터)
------------------------------------------------------------------------ */

-- 1) 키워드 총량/최근 생성 날짜
SELECT COUNT(*) AS keyword_cnt, MAX(CREATED_AT) AS last_created_at
FROM T_TREND_KEYWORD_MASTER;

-- 2) KEYWORD_NAME 중복(0건 정상: UNIQUE)
SELECT KEYWORD_NAME, COUNT(*) AS cnt
FROM T_TREND_KEYWORD_MASTER
GROUP BY KEYWORD_NAME
HAVING cnt > 1;

-- 3) 키워드명 공백/이상치(0건 정상)
SELECT KEYWORD_SEQ, KEYWORD_NAME
FROM T_TREND_KEYWORD_MASTER
WHERE KEYWORD_NAME IS NULL OR TRIM(KEYWORD_NAME) = '';


/* ----------------------------------------------------------------------
  3) T_TREND_RUN (트렌드 실행)
------------------------------------------------------------------------ */

-- 1) 최신 run 목록 확인
SELECT TREND_RUN_SEQ, BASE_DATE, RUN_AT, TOP_N
FROM T_TREND_RUN
ORDER BY TREND_RUN_SEQ DESC
LIMIT 20;

-- 1-1) 특정 TREND_RUN_SEQ의 키워드 목록(순위 포함)
SELECT
  s.TREND_RUN_SEQ,
  s.TREND_RANK,
  s.KEYWORD_SEQ,
  km.KEYWORD_NAME
FROM T_TREND_KEYWORD_SNAPSHOT s
JOIN T_TREND_KEYWORD_MASTER km
  ON km.KEYWORD_SEQ = s.KEYWORD_SEQ
WHERE s.TREND_RUN_SEQ = @run_seq
ORDER BY s.TREND_RANK ASC;

-- 2) 같은 BASE_DATE가 여러 run으로 쌓였는지(정상일 수도 있음)
-- 예를들어 하루에 여러번 크롤링 및 분석 돌리면 cnt가 1보다 큼
SELECT BASE_DATE,
       COUNT(*) AS cnt,
       MIN(TREND_RUN_SEQ) AS min_trend_run_seq,
       MAX(TREND_RUN_SEQ) AS max_trend_run_seq
FROM T_TREND_RUN
GROUP BY BASE_DATE
ORDER BY BASE_DATE DESC
LIMIT 30;


/* ----------------------------------------------------------------------
  4) T_TREND_KEYWORD_SNAPSHOT (트렌드 스냅샷)
------------------------------------------------------------------------ */

-- 1) run별 스냅샷 행 수(Top N 개수와 맞는지)
SELECT TREND_RUN_SEQ,
       COUNT(*) AS snapshot_cnt,
       MIN(TREND_RANK) AS min_rank,
       MAX(TREND_RANK) AS max_rank
FROM T_TREND_KEYWORD_SNAPSHOT
GROUP BY TREND_RUN_SEQ
ORDER BY TREND_RUN_SEQ DESC
LIMIT 20;

-- 2) 현재 run(@run_seq)의 rank 연속성 체크(빠진 순위가 있는지)
-- 0건 정상
-- (개선) 1..MAX(TREND_RANK)까지 동적으로 생성해서 200 고정 한계를 제거
WITH RECURSIVE seq AS (
  SELECT 1 AS n
  UNION ALL
  SELECT n + 1
  FROM seq
  WHERE n < (
    SELECT COALESCE(MAX(TREND_RANK), 0)
    FROM T_TREND_KEYWORD_SNAPSHOT
    WHERE TREND_RUN_SEQ = @run_seq
  )
)
SELECT seq.n AS missing_rank
FROM seq
LEFT JOIN T_TREND_KEYWORD_SNAPSHOT s
  ON s.TREND_RUN_SEQ = @run_seq AND s.TREND_RANK = seq.n
WHERE s.TREND_RANK IS NULL
ORDER BY missing_rank;

-- 3) 중복(0건 정상: UNIQUE 제약)
SELECT TREND_RUN_SEQ, TREND_RANK, COUNT(*) AS cnt
FROM T_TREND_KEYWORD_SNAPSHOT
GROUP BY TREND_RUN_SEQ, TREND_RANK
HAVING cnt > 1;

SELECT TREND_RUN_SEQ, KEYWORD_SEQ, COUNT(*) AS cnt
FROM T_TREND_KEYWORD_SNAPSHOT
GROUP BY TREND_RUN_SEQ, KEYWORD_SEQ
HAVING cnt > 1;

-- 4) 스냅샷이 참조하는 키워드가 마스터에 있는지(0건 정상)
SELECT s.*
FROM T_TREND_KEYWORD_SNAPSHOT s
LEFT JOIN T_TREND_KEYWORD_MASTER k ON k.KEYWORD_SEQ = s.KEYWORD_SEQ
WHERE s.TREND_RUN_SEQ = @run_seq AND k.KEYWORD_SEQ IS NULL;


/* ----------------------------------------------------------------------
  5) T_NEWS_ARTICLE (기사)
------------------------------------------------------------------------ */

-- 1) 특정 run(@run_seq): 키워드별 기사 수(기간 조건 없음)
-- 0건인 기사는 안 뜬다.
SELECT
  a.TREND_RUN_SEQ,
  a.KEYWORD_SEQ,
  km.KEYWORD_NAME,
  COUNT(*) AS article_cnt,
  MIN(a.PUBLISHED_AT) AS min_published_at,
  MAX(a.PUBLISHED_AT) AS max_published_at
FROM T_NEWS_ARTICLE a
JOIN T_TREND_KEYWORD_MASTER km
  ON km.KEYWORD_SEQ = a.KEYWORD_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq
GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ, km.KEYWORD_NAME
ORDER BY article_cnt DESC;


-- 2) 언론사별 기사 수(기간 조건 없음: run에 적재된 전체 -> 사실상 D14 기준)
SELECT t.MEDIA_CODE,
       COALESCE(m.MEDIA_NAME, CASE WHEN t.MEDIA_CODE = 0 THEN '전체' ELSE NULL END) AS MEDIA_NAME,
       t.article_cnt
FROM (
  SELECT 0 AS MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE
  WHERE TREND_RUN_SEQ = @run_seq

  UNION ALL

  SELECT MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE
  WHERE TREND_RUN_SEQ = @run_seq
  GROUP BY MEDIA_CODE
) AS t
LEFT JOIN T_NEWS_MEDIA AS m ON m.MEDIA_CODE = t.MEDIA_CODE
ORDER BY (t.MEDIA_CODE = 0) DESC, t.article_cnt DESC;

-- 2-1) 언론사별 TODAY 기사 수(BASE_DATE 기준)
SELECT t.MEDIA_CODE,
       COALESCE(m.MEDIA_NAME, CASE WHEN t.MEDIA_CODE = 0 THEN '전체' ELSE NULL END) AS MEDIA_NAME,
       t.article_cnt
FROM (
  SELECT 0 AS MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT >= TIMESTAMP(r.BASE_DATE)
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))

  UNION ALL

  SELECT a.MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT >= TIMESTAMP(r.BASE_DATE)
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.MEDIA_CODE
) AS t
LEFT JOIN T_NEWS_MEDIA AS m ON m.MEDIA_CODE = t.MEDIA_CODE
ORDER BY (t.MEDIA_CODE = 0) DESC, t.article_cnt DESC;

-- 2-2) 언론사별 D7 기사 수(BASE_DATE 기준, 오늘 포함 7일)
SELECT t.MEDIA_CODE,
       COALESCE(m.MEDIA_NAME, CASE WHEN t.MEDIA_CODE = 0 THEN '전체' ELSE NULL END) AS MEDIA_NAME,
       t.article_cnt
FROM (
  SELECT 0 AS MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 6 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))

  UNION ALL

  SELECT a.MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 6 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.MEDIA_CODE
) AS t
LEFT JOIN T_NEWS_MEDIA AS m ON m.MEDIA_CODE = t.MEDIA_CODE
ORDER BY (t.MEDIA_CODE = 0) DESC, t.article_cnt DESC;

-- 2-3) 언론사별 D14 기사 수(BASE_DATE 기준, 오늘 포함 14일)
SELECT t.MEDIA_CODE,
       COALESCE(m.MEDIA_NAME, CASE WHEN t.MEDIA_CODE = 0 THEN '전체' ELSE NULL END) AS MEDIA_NAME,
       t.article_cnt
FROM (
  SELECT 0 AS MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 13 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))

  UNION ALL

  SELECT a.MEDIA_CODE, COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 13 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.MEDIA_CODE
) AS t
LEFT JOIN T_NEWS_MEDIA AS m ON m.MEDIA_CODE = t.MEDIA_CODE
ORDER BY (t.MEDIA_CODE = 0) DESC, t.article_cnt DESC;

-- 3) 키워드별 기사 수(기간조건 없음 -> 사실상 D14 기준)
SELECT
  a.KEYWORD_SEQ,
  k.KEYWORD_NAME,
  COUNT(*) AS article_cnt
FROM T_NEWS_ARTICLE a
LEFT JOIN T_TREND_KEYWORD_MASTER k ON k.KEYWORD_SEQ = a.KEYWORD_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq
GROUP BY a.KEYWORD_SEQ, k.KEYWORD_NAME
ORDER BY article_cnt DESC, a.KEYWORD_SEQ ASC;

-- 3-1) 키워드별 TODAY 기사 수(BASE_DATE 기준)
SELECT
  a.KEYWORD_SEQ,
  k.KEYWORD_NAME,
  COUNT(*) AS article_cnt
FROM T_NEWS_ARTICLE a
JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
LEFT JOIN T_TREND_KEYWORD_MASTER k ON k.KEYWORD_SEQ = a.KEYWORD_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq
  AND a.PUBLISHED_AT >= TIMESTAMP(r.BASE_DATE)
  AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
GROUP BY a.KEYWORD_SEQ, k.KEYWORD_NAME
ORDER BY article_cnt DESC, a.KEYWORD_SEQ ASC;

-- 3-2) 키워드별 D7 기사 수(BASE_DATE 기준, 오늘 포함 7일)
SELECT
  a.KEYWORD_SEQ,
  k.KEYWORD_NAME,
  COUNT(*) AS article_cnt
FROM T_NEWS_ARTICLE a
JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
LEFT JOIN T_TREND_KEYWORD_MASTER k ON k.KEYWORD_SEQ = a.KEYWORD_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq
  AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 6 DAY))
  AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
GROUP BY a.KEYWORD_SEQ, k.KEYWORD_NAME
ORDER BY article_cnt DESC, a.KEYWORD_SEQ ASC;

-- 3-3) 키워드별 D14 기사 수(BASE_DATE 기준, 오늘 포함 14일)
SELECT
  a.KEYWORD_SEQ,
  k.KEYWORD_NAME,
  COUNT(*) AS article_cnt
FROM T_NEWS_ARTICLE a
JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
LEFT JOIN T_TREND_KEYWORD_MASTER k ON k.KEYWORD_SEQ = a.KEYWORD_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq
  AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 13 DAY))
  AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
GROUP BY a.KEYWORD_SEQ, k.KEYWORD_NAME
ORDER BY article_cnt DESC, a.KEYWORD_SEQ ASC;

-- 4) URL_HASH 중복(0건 정상: UNIQUE(RUN,KEYWORD,URL_HASH))
SELECT TREND_RUN_SEQ, KEYWORD_SEQ, URL_HASH, COUNT(*) AS cnt
FROM T_NEWS_ARTICLE
WHERE TREND_RUN_SEQ = @run_seq
GROUP BY TREND_RUN_SEQ, KEYWORD_SEQ, URL_HASH
HAVING cnt > 1;

-- 5) 필수값 누락/이상치 점검(0건 정상)
SELECT ARTICLE_SEQ, SOURCE_URL, URL_HASH, TITLE, MEDIA_CODE, KEYWORD_SEQ, TREND_RUN_SEQ
FROM T_NEWS_ARTICLE
WHERE TREND_RUN_SEQ = @run_seq
  AND (
    SOURCE_URL IS NULL OR TRIM(SOURCE_URL) = ''
    OR URL_HASH IS NULL OR CHAR_LENGTH(URL_HASH) <> 64
    OR TITLE IS NULL OR TRIM(TITLE) = ''
  )
LIMIT 200;

-- 5-1) URL_HASH 포맷이 64 hex가 아닌 경우(0건 정상)
SELECT ARTICLE_SEQ, URL_HASH
FROM T_NEWS_ARTICLE
WHERE TREND_RUN_SEQ = @run_seq
  AND (URL_HASH IS NULL OR URL_HASH NOT REGEXP '^[0-9a-fA-F]{64}$')
LIMIT 200;

-- 6) 전처리 상태 점검(클린 컬럼 결측 수)
-- 0건 정상
SELECT
  SUM(CASE WHEN TITLE_CLEAN IS NULL OR TRIM(TITLE_CLEAN) = '' THEN 1 ELSE 0 END) AS title_clean_missing,
  SUM(CASE WHEN CONTENT_CLEAN IS NULL OR TRIM(CONTENT_CLEAN) = '' THEN 1 ELSE 0 END) AS content_clean_missing,
  COUNT(*) AS total
FROM T_NEWS_ARTICLE
WHERE TREND_RUN_SEQ = @run_seq;

-- 7) 기사 FK 무결성(원칙상 0건)
SELECT a.ARTICLE_SEQ
FROM T_NEWS_ARTICLE a
LEFT JOIN T_NEWS_MEDIA m ON m.MEDIA_CODE = a.MEDIA_CODE
LEFT JOIN T_TREND_KEYWORD_MASTER k ON k.KEYWORD_SEQ = a.KEYWORD_SEQ
LEFT JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq
  AND (m.MEDIA_CODE IS NULL OR k.KEYWORD_SEQ IS NULL OR r.TREND_RUN_SEQ IS NULL)
LIMIT 200;


/* ----------------------------------------------------------------------
  6) T_NEWS_COMMENT (댓글)
------------------------------------------------------------------------ */

-- 1) 기사당 댓글 수 분포(상위)
SELECT ARTICLE_SEQ, COUNT(*) AS comment_cnt
FROM T_NEWS_COMMENT
GROUP BY ARTICLE_SEQ
ORDER BY comment_cnt DESC
LIMIT 50;

-- 2) 중복 댓글(0건 정상: UNIQUE(ARTICLE_SEQ, COMMENT_HASH))
SELECT ARTICLE_SEQ, COMMENT_HASH, COUNT(*) AS cnt
FROM T_NEWS_COMMENT
GROUP BY ARTICLE_SEQ, COMMENT_HASH
HAVING cnt > 1;

-- 3) 고아 댓글(원칙상 0건: 기사 FK)
SELECT c.COMMENT_SEQ, c.ARTICLE_SEQ
FROM T_NEWS_COMMENT c
LEFT JOIN T_NEWS_ARTICLE a ON a.ARTICLE_SEQ = c.ARTICLE_SEQ
WHERE a.ARTICLE_SEQ IS NULL
LIMIT 200;

-- 4) 전처리 상태 점검(0건이 이상적 목표이긴 하나 케이스에 따라 0이 아닐 수 있음)
-- 예를들어 이모티콘 등만 있는 댓글 같은 경우
-- (개선) run 기준으로만 집계해서 "이번 run" 품질을 정확히 보기
SELECT
  SUM(CASE WHEN c.COMMENT_CLEAN IS NULL OR TRIM(c.COMMENT_CLEAN) = '' THEN 1 ELSE 0 END) AS comment_clean_missing,
  COUNT(*) AS total
FROM T_NEWS_COMMENT c
JOIN T_NEWS_ARTICLE a ON a.ARTICLE_SEQ = c.ARTICLE_SEQ
WHERE a.TREND_RUN_SEQ = @run_seq;


/* ----------------------------------------------------------------------
  7) T_TREND_KEYWORD_FINAL_RANK (최종 순위)
------------------------------------------------------------------------ */

-- 1) run/period 별 최종 순위 개수/최대랭크
SELECT TREND_RUN_SEQ, PERIOD_FILTER,
       COUNT(*) AS rows_cnt,
       MIN(FINAL_RANK) AS min_rank,
       MAX(FINAL_RANK) AS max_rank
FROM T_TREND_KEYWORD_FINAL_RANK
WHERE TREND_RUN_SEQ = @run_seq
GROUP BY TREND_RUN_SEQ, PERIOD_FILTER;

-- 2) FINAL_RANK 중복(0건이 이상적)
SELECT TREND_RUN_SEQ, PERIOD_FILTER, FINAL_RANK, COUNT(*) AS cnt
FROM T_TREND_KEYWORD_FINAL_RANK
WHERE TREND_RUN_SEQ = @run_seq
GROUP BY TREND_RUN_SEQ, PERIOD_FILTER, FINAL_RANK
HAVING cnt > 1;

-- 3) 최종순위 + 키워드명 + 키워드 전체 기사수(TODAY/D7/D14, BASE_DATE 기준)
SELECT
  f.TREND_RUN_SEQ,
  f.PERIOD_FILTER,
  f.FINAL_RANK,
  f.KEYWORD_SEQ,
  km.KEYWORD_NAME,
  COALESCE(a.article_cnt, 0) AS article_cnt_in_period
FROM T_TREND_KEYWORD_FINAL_RANK f
JOIN T_TREND_KEYWORD_MASTER km
  ON km.KEYWORD_SEQ = f.KEYWORD_SEQ
LEFT JOIN (
  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    'TODAY' AS PERIOD_FILTER,
    COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT IS NOT NULL
    AND a.PUBLISHED_AT >= TIMESTAMP(r.BASE_DATE)
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ

  UNION ALL

  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    'D7' AS PERIOD_FILTER,
    COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT IS NOT NULL
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 6 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ

  UNION ALL

  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    'D14' AS PERIOD_FILTER,
    COUNT(*) AS article_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT IS NOT NULL
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 13 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ
) a
  ON a.TREND_RUN_SEQ = f.TREND_RUN_SEQ
 AND a.KEYWORD_SEQ   = f.KEYWORD_SEQ
 AND a.PERIOD_FILTER = f.PERIOD_FILTER
WHERE f.TREND_RUN_SEQ = @run_seq
ORDER BY f.PERIOD_FILTER, f.FINAL_RANK;

-- 4) 최종순위 + 키워드명 + 언론사별 TODAY/D7/D14 기사수(BASE_DATE 기준)
SELECT
  f.TREND_RUN_SEQ,
  f.PERIOD_FILTER,
  f.FINAL_RANK,
  f.KEYWORD_SEQ,
  km.KEYWORD_NAME,
  a.MEDIA_CODE,
  m.MEDIA_NAME,
  CASE
    WHEN f.PERIOD_FILTER = 'TODAY' THEN COALESCE(a.today_cnt, 0)
    WHEN f.PERIOD_FILTER = 'D7'    THEN COALESCE(a.d7_cnt, 0)
    WHEN f.PERIOD_FILTER = 'D14'   THEN COALESCE(a.d14_cnt, 0)
    ELSE 0
  END AS article_cnt_in_period
FROM T_TREND_KEYWORD_FINAL_RANK f
JOIN T_TREND_KEYWORD_MASTER km
  ON km.KEYWORD_SEQ = f.KEYWORD_SEQ
LEFT JOIN (
  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    a.MEDIA_CODE,
    SUM(
      CASE
        WHEN a.PUBLISHED_AT IS NOT NULL
         AND a.PUBLISHED_AT >= TIMESTAMP(r.BASE_DATE)
         AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
        THEN 1 ELSE 0
      END
    ) AS today_cnt,
    SUM(
      CASE
        WHEN a.PUBLISHED_AT IS NOT NULL
         AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 6 DAY))
         AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
        THEN 1 ELSE 0
      END
    ) AS d7_cnt,
    SUM(
      CASE
        WHEN a.PUBLISHED_AT IS NOT NULL
         AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r.BASE_DATE, INTERVAL 13 DAY))
         AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r.BASE_DATE, INTERVAL 1 DAY))
        THEN 1 ELSE 0
      END
    ) AS d14_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r ON r.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ, a.MEDIA_CODE
) a
  ON a.TREND_RUN_SEQ = f.TREND_RUN_SEQ
 AND a.KEYWORD_SEQ   = f.KEYWORD_SEQ
LEFT JOIN T_NEWS_MEDIA m
  ON m.MEDIA_CODE = a.MEDIA_CODE
WHERE f.TREND_RUN_SEQ = @run_seq
ORDER BY f.PERIOD_FILTER, f.FINAL_RANK, article_cnt_in_period DESC, a.MEDIA_CODE;

-- 5) FINAL_RANK의 ARTICLE_COUNT가 실제 기사 수(BASE_DATE 기준 TODAY/D7/D14)와 맞는지(0건 정상)
SELECT
  f.TREND_RUN_SEQ,
  f.PERIOD_FILTER,
  f.FINAL_RANK,
  f.KEYWORD_SEQ,
  km.KEYWORD_NAME,
  f.ARTICLE_COUNT AS stored_cnt,
  COALESCE(a.real_cnt, 0) AS real_cnt
FROM T_TREND_KEYWORD_FINAL_RANK f
JOIN T_TREND_RUN r
  ON r.TREND_RUN_SEQ = f.TREND_RUN_SEQ
JOIN T_TREND_KEYWORD_MASTER km
  ON km.KEYWORD_SEQ = f.KEYWORD_SEQ
LEFT JOIN (
  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    'TODAY' AS PERIOD_FILTER,
    COUNT(*) AS real_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r2 ON r2.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT IS NOT NULL
    AND a.PUBLISHED_AT >= TIMESTAMP(r2.BASE_DATE)
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r2.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ

  UNION ALL

  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    'D7' AS PERIOD_FILTER,
    COUNT(*) AS real_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r2 ON r2.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT IS NOT NULL
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r2.BASE_DATE, INTERVAL 6 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r2.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ

  UNION ALL

  SELECT
    a.TREND_RUN_SEQ,
    a.KEYWORD_SEQ,
    'D14' AS PERIOD_FILTER,
    COUNT(*) AS real_cnt
  FROM T_NEWS_ARTICLE a
  JOIN T_TREND_RUN r2 ON r2.TREND_RUN_SEQ = a.TREND_RUN_SEQ
  WHERE a.TREND_RUN_SEQ = @run_seq
    AND a.PUBLISHED_AT IS NOT NULL
    AND a.PUBLISHED_AT >= TIMESTAMP(DATE_SUB(r2.BASE_DATE, INTERVAL 13 DAY))
    AND a.PUBLISHED_AT <  TIMESTAMP(DATE_ADD(r2.BASE_DATE, INTERVAL 1 DAY))
  GROUP BY a.TREND_RUN_SEQ, a.KEYWORD_SEQ
) a
  ON a.TREND_RUN_SEQ = f.TREND_RUN_SEQ
 AND a.KEYWORD_SEQ   = f.KEYWORD_SEQ
 AND a.PERIOD_FILTER = f.PERIOD_FILTER
WHERE f.TREND_RUN_SEQ = @run_seq
  AND COALESCE(a.real_cnt, 0) <> COALESCE(f.ARTICLE_COUNT, 0)
ORDER BY f.PERIOD_FILTER, f.FINAL_RANK
LIMIT 200;

-- 6) (추가) 스냅샷 키워드 대비 FINAL_RANK가 누락된 조합이 있는지(0건 정상)
-- 키워드마다 TODAY/D7/D14 모두 만들어야 한다는 전제라면, 누락을 빠르게 찾을 수 있음
WITH periods AS (
  SELECT 'TODAY' AS PERIOD_FILTER
  UNION ALL SELECT 'D7'
  UNION ALL SELECT 'D14'
)
SELECT
  s.TREND_RUN_SEQ,
  s.KEYWORD_SEQ,
  km.KEYWORD_NAME,
  p.PERIOD_FILTER
FROM T_TREND_KEYWORD_SNAPSHOT s
