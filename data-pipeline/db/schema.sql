-- MySQL 8.x / utf8mb4 기준

-- 문자 인코딩을 utf8mb4로 쓰겠다는 뜻
SET NAMES utf8mb4;

-- 시간대(타임존)를 한국으로 맞춤
SET time_zone = '+09:00';


-- FK 때문에 생성 순서 중요 (T_NEWS_MEDIA -> T_TREND_KEYWORD_MASTER -> T_NEWS_ARTICLE -> ...)
-- 실제 실행(적용) 순서: DDL을 작성한 순서
-- 1. 뉴스 관련 데이터 저장 테이블 모음
