-- (3) 감성 분석(T_ANALYZE_SENTIMENT)
-- 제목 기반 비율: *_PCT_TITLE
-- 본문 기반 비율: *_PCT_CONTENT
-- 여기서 제목/본문을 ENUM('TITLE','CONTENT'), ENUM('POSITIVE' ,'NEUTRAL', 'NEGATIVE')으로 할 수도 있었지만 그냥 따로 행 만듦
-- DECIMAL(전체 자리수, 소수점 자리수)
-- DECIMAL(5,2) => 최대 999.99까지 가능
-- DECIMAL(7,2) => 최대 99999.99까지 가능
-- DECIMAL(7,4) => 최대 999.9999까지 가능. 9999.999 같은건 안됨. 소수점은 무조건 4자리 확정이고 남은 3자리만 정수 자리 사용가능
CREATE TABLE IF NOT EXISTS T_ANALYZE_SENTIMENT (
  SENTIMENT_SEQ BIGINT NOT NULL AUTO_INCREMENT,
  TREND_RUN_SEQ BIGINT NOT NULL,
  KEYWORD_SEQ BIGINT NOT NULL,
  MEDIA_CODE INT NOT NULL DEFAULT 0,              
  PERIOD_FILTER ENUM('TODAY','D7','D14','D30') NOT NULL,
  POSITIVE_PCT_TITLE DECIMAL(5,2) NOT NULL DEFAULT 0,
  NEUTRAL_PCT_TITLE  DECIMAL(5,2) NOT NULL DEFAULT 0,
  NEGATIVE_PCT_TITLE DECIMAL(5,2) NOT NULL DEFAULT 0,
  POSITIVE_PCT_CONTENT DECIMAL(5,2) NOT NULL DEFAULT 0,
  NEUTRAL_PCT_CONTENT  DECIMAL(5,2) NOT NULL DEFAULT 0,
  NEGATIVE_PCT_CONTENT DECIMAL(5,2) NOT NULL DEFAULT 0,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

  -- PK: 감성 일련번호
  PRIMARY KEY (SENTIMENT_SEQ),

  -- 조회 성능용 인덱스
  KEY IX_T_KSENT__RUN (TREND_RUN_SEQ),
  KEY IX_T_KSENT__KEYWORD (KEYWORD_SEQ),
  KEY IX_T_KSENT__MEDIA (MEDIA_CODE),

  -- 중복 방지
  UNIQUE KEY UK_T_KSENT__RUN_KMP (TREND_RUN_SEQ, KEYWORD_SEQ, MEDIA_CODE, PERIOD_FILTER),

  -- FK: 트렌드 일련번호
  CONSTRAINT FK_T_KSENT__RUN
    FOREIGN KEY (TREND_RUN_SEQ) REFERENCES T_TREND_RUN (TREND_RUN_SEQ)
    ON UPDATE RESTRICT ON DELETE CASCADE,

  -- FK: 키워드 일련번호
  CONSTRAINT FK_T_KSENT__KEYWORD
    FOREIGN KEY (KEYWORD_SEQ) REFERENCES T_TREND_KEYWORD_MASTER (KEYWORD_SEQ)
    ON UPDATE RESTRICT ON DELETE RESTRICT,

  -- FK: 언론사 코드
  CONSTRAINT FK_T_KSENT__MEDIA
    FOREIGN KEY (MEDIA_CODE) REFERENCES T_NEWS_MEDIA (MEDIA_CODE)
    ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;


-- (4) 언론사별 편향도 지수(T_ANALYZE_MEDIA_BIAS) 테이블 생성
